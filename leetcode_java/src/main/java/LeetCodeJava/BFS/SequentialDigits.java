package LeetCodeJava.BFS;

// https://leetcode.com/problems/sequential-digits/description/

import java.util.*;

/**
 * 1291. Sequential Digits
 * Medium
 *
 * An integer has sequential digits if and only if each digit in the number
 * is one more than the previous digit.
 *
 * Return a sorted list of all the integers in the range [low, high] inclusive
 * that have sequential digits.
 *
 *
 * Example 1:
 *
 * Input: low = 100, high = 300
 * Output: [123,234]
 *
 * Example 2:
 *
 * Input: low = 1000, high = 13000
 * Output: [1234,2345,3456,4567,5678,6789,12345]
 *
 *
 * Constraints:
 *
 * 10 <= low <= high <= 10^9
 *
 */
public class SequentialDigits {

    // V0
    // IDEA: ENUMERATE ALL SEQUENTIAL NUMBERS (THERE ARE ONLY 36 WITH 2+ DIGITS)
    //  a sequential number is fixed by its first digit and its length:
    //  extend with value = value * 10 + nextDigit, keep those in range, then sort.
    /**
     * time = O(1)
     * space = O(1)
     */
    public List<Integer> sequentialDigits(int low, int high) {
        List<Integer> result = new ArrayList<>();
        for (int firstDigit = 1; firstDigit <= 9; firstDigit++) {
            // the largest candidate is 123456789, which fits in an int
            int value = firstDigit;
            for (int nextDigit = firstDigit + 1; nextDigit <= 9; nextDigit++) {
                value = value * 10 + nextDigit;
                if (value >= low && value <= high) {
                    result.add(value);
                }
            }
        }
        // generated by first digit, not by size -> sort
        Collections.sort(result);
        return result;
    }

    // V1
    // IDEA: BFS (LEVEL = NUMBER OF DIGITS)
    //  seed 1..9; each popped value extends only by (lastDigit + 1).
    //  BFS pops shorter numbers first, and within a length in increasing order,
    //  so the output is already sorted.
    /**
     * time = O(1)
     * space = O(1)
     */
    public List<Integer> sequentialDigits_1(int low, int high) {
        List<Integer> result = new ArrayList<>();
        Deque<Long> queue = new ArrayDeque<>();
        for (long digit = 1; digit <= 9; digit++) {
            queue.offer(digit);
        }
        while (!queue.isEmpty()) {
            long current = queue.poll();
            if (current >= low && current <= high) {
                result.add((int) current);
            }
            long lastDigit = current % 10;
            // only lastDigit + 1 may follow, and only when lastDigit < 9
            if (lastDigit < 9) {
                long next = current * 10 + lastDigit + 1;
                if (next <= high) {
                    queue.offer(next);
                }
            }
        }
        return result;
    }
}
